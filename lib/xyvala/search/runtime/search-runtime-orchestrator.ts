function validateRawDocuments(
  rawDocuments:
    readonly SearchRawDocument[],
): void {
  const documentIds =
    new Set<SearchDocumentId>();

  for (
    const [
      index,
      rawDocument,
    ] of rawDocuments.entries()
  ) {
    const fieldName =
      `raw_documents[${String(index)}]`;

    validateDocumentContract(
      rawDocument,
      rawDocument.document_id,
      fieldName,
    );

    assertNonEmptyString(
      rawDocument.source_uri,
      `${fieldName}.source_uri`,
    );

    assertValidIsoTimestamp(
      rawDocument.fetched_at,
      `${fieldName}.fetched_at`,
    );

    assertNonEmptyString(
      rawDocument.content_hash,
      `${fieldName}.content_hash`,
    );

    validateOptionalIsoTimestampEvidence(
      rawDocument.source_published_at,
      `${fieldName}.source_published_at`,
    );

    if (
      documentIds.has(
        rawDocument.document_id,
      )
    ) {
      throw new Error(
        `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
          `Boundary violation: duplicate acquired document identity ${rawDocument.document_id}.`,
      );
    }

    documentIds.add(
      rawDocument.document_id,
    );
  }
}

/* ============================================================================
 * 30. INTRINSIC DOCUMENT PIPELINE
 * ========================================================================== */

async function runIntrinsicDocumentPipeline(
  rawDocument:
    SearchRawDocument,

  query:
    SearchQuery,

  createdAt:
    SearchIsoTimestamp,

  publicationReferenceAt:
    SearchIsoTimestamp,

  ports:
    SearchRuntimePorts,
): Promise<SearchRuntimeIntrinsicDocumentState> {
  const documentId =
    rawDocument.document_id;

  const extractedDocument =
    await ports.extract_document({
      raw_document:
        rawDocument,

      created_at:
        createdAt,
    });

  validateDocumentContract(
    extractedDocument,
    documentId,
    "extracted_document",
  );

  const segmentedDocument =
    await ports.segment_document({
      extracted_document:
        extractedDocument,

      created_at:
        createdAt,
    });

  validateDocumentContract(
    segmentedDocument,
    documentId,
    "segmented_document",
  );

  const lexicalDocument =
    await ports.analyze_lexical_document({
      extracted_document:
        extractedDocument,

      segmented_document:
        segmentedDocument,

      created_at:
        createdAt,
    });

  validateDocumentContract(
    lexicalDocument,
    documentId,
    "lexical_document",
  );

  const frequencySignals =
    await ports.detect_frequency_signals({
      lexical_document:
        lexicalDocument,

      created_at:
        createdAt,
    });

  validateDocumentContract(
    frequencySignals,
    documentId,
    "frequency_signals",
  );

  const intrinsicAnchorSignals =
    await ports.detect_anchor_signals({
      segmented_document:
        segmentedDocument,

      lexical_document:
        lexicalDocument,

      frequency_signals:
        frequencySignals,

      created_at:
        createdAt,
    });

  validateDocumentContract(
    intrinsicAnchorSignals,
    documentId,
    "intrinsic_anchor_signals",
  );

  const contextAggregation =
    await ports.aggregate_context({
      segmented_document:
        segmentedDocument,

      frequency_signals:
        frequencySignals,

      intrinsic_anchor_signals:
        intrinsicAnchorSignals,

      created_at:
        createdAt,
    });

  validateDocumentContract(
    contextAggregation,
    documentId,
    "context_aggregation",
  );

  const linkSignals =
    await ports.detect_link_signals({
      raw_document:
        rawDocument,

      extracted_document:
        extractedDocument,

      created_at:
        createdAt,
    });

  validateDocumentContract(
    linkSignals,
    documentId,
    "link_signals",
  );

  const temporalSignals =
    await ports.detect_temporal_signals({
      raw_document:
        rawDocument,

      frequency_signals:
        frequencySignals,

      intrinsic_anchor_signals:
        intrinsicAnchorSignals,

      context_aggregation:
        contextAggregation,

      created_at:
        createdAt,

      publication_reference_at:
        publicationReferenceAt,
    });

  validateDocumentContract(
    temporalSignals,
    documentId,
    "temporal_signals",
  );

  assertOptionalIsoTimestampPropagation(
    rawDocument.source_published_at,
    temporalSignals.published_at,
    "temporal_signals.published_at",
  );

  const behavioralSignals =
    await ports.detect_behavioral_signals({
      query,

      raw_document:
        rawDocument,

      created_at:
        createdAt,
    });

  validateDocumentContract(
    behavioralSignals,
    documentId,
    "behavioral_signals",
  );

  assertQueryScope(
    behavioralSignals.query_id,
    query.query_id,
    "behavioral_signals",
  );

  return Object.freeze({
    raw_document:
      rawDocument,

    extracted_document:
      extractedDocument,

    segmented_document:
      segmentedDocument,

    lexical_document:
      lexicalDocument,

    frequency_signals:
      frequencySignals,

    intrinsic_anchor_signals:
      intrinsicAnchorSignals,

    context_aggregation:
      contextAggregation,

    link_signals:
      linkSignals,

    temporal_signals:
      temporalSignals,

    behavioral_signals:
      behavioralSignals,
  });
}

