function assertNonEmptyString(
  value:
    string,

  fieldName:
    string,
): void {
  if (
    typeof value !==
      "string" ||
    value.trim().length ===
      0
  ) {
    throw new Error(
      `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
        `Contract violation: ${fieldName} must be a non-empty string.`,
    );
  }
}

function assertValidIsoTimestamp(
  value:
    SearchIsoTimestamp,

  fieldName:
    string,
): void {
  assertNonEmptyString(
    value,
    fieldName,
  );

  if (
    !Number.isFinite(
      Date.parse(
        value,
      ),
    )
  ) {
    throw new Error(
      `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
        `Contract violation: ${fieldName} must be a valid ISO timestamp.`,
    );
  }
}

/* ============================================================================
 * 21. OPTIONAL TIMESTAMP EVIDENCE VALIDATION
 * ========================================================================== */

function validateOptionalIsoTimestampEvidence(
  evidence:
    SearchOptionalEvidence<SearchIsoTimestamp>,

  fieldName:
    string,
): void {
  if (
    evidence.availability_state ===
      "AVAILABLE"
  ) {
    assertValidIsoTimestamp(
      evidence.value,
      `${fieldName}.value`,
    );

    return;
  }

  assertNonEmptyString(
    evidence.reason,
    `${fieldName}.reason`,
  );
}

/* ============================================================================
 * 22. OPTIONAL TIMESTAMP PROPAGATION
 * ----------------------------------------------------------------------------
 * Semantic propagation only.
 *
 * No envelope is reconstructed.
 * ========================================================================== */

function assertOptionalIsoTimestampPropagation(
  expected:
    SearchOptionalEvidence<SearchIsoTimestamp>,

  actual:
    SearchOptionalEvidence<SearchIsoTimestamp>,

  fieldName:
    string,
): void {
  if (
    actual.availability_state !==
    expected.availability_state
  ) {
    throw new Error(
      `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
        `First divergence: ${fieldName} changed canonical availability state.`,
    );
  }

  if (
    expected.availability_state ===
      "AVAILABLE" &&
    actual.availability_state ===
      "AVAILABLE"
  ) {
    if (
      actual.value !==
      expected.value
    ) {
      throw new Error(
        `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
          `First divergence: ${fieldName} changed canonical timestamp value.`,
      );
    }

    return;
  }

  if (
    expected.availability_state !==
      "AVAILABLE" &&
    actual.availability_state !==
      "AVAILABLE" &&
    actual.reason !==
      expected.reason
  ) {
    throw new Error(
      `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
        `First divergence: ${fieldName} changed canonical unavailability reason.`,
    );
  }
}

