/* ============================================================================
 * FILE: lib/xyvala/search/runtime/search-runtime-orchestrator.ts
 * ----------------------------------------------------------------------------
 * TITLE
 * - Xyvala Search canonical runtime orchestrator
 *
 * ROLE
 * - execute the canonical Xyvala Search runtime pipeline
 * - enforce official producer ordering
 * - preserve canonical document, query, cohort and distribution identities
 * - transport canonical truth between authorized producers
 * - transport explicit publication temporal provenance
 * - transport the explicit analytical publication reference timestamp
 * - validate propagation boundaries at first divergence
 * - establish SearchCohortBatch before Cohort Normalization
 * - preserve explicit unavailable cohort / relative evidence
 * - preserve explicit optional Link Authority / Behavioral Calibration evidence
 * - propagate canonical QueryProfile into Query Relevance Scoring
 * - preserve canonical SearchCohortCandidate references through the cohort path
 * - enforce ranking participation before public transformation
 * - assemble the final SearchPublicRankingProjection through canonical ports
 *
 * CLASSIFICATION
 * - SEARCH RUNTIME ORCHESTRATOR
 * - SEARCH DOMAIN
 * - ORCHESTRATION
 * - EXECUTION COORDINATION
 * - TRANSPORT / VALIDATE / SEQUENCE
 * - NON-ANALYTICAL
 * - NON-SCORING
 * - NON-RANKING
 * - NON-TRANSFORMING
 * - NON-CALIBRATING
 * - NON-IDENTITY-PRODUCING
 * - NON-TRACE-PRODUCING
 * - NON-MUTATING
 * - DETERMINISTIC GIVEN DETERMINISTIC PORTS
 *
 * POSITION IN OFFICIAL CHAIN
 * ----------------------------------------------------------------------------
 *
 * ACQUISITION
 * -> EXTRACTION
 * -> SEGMENTATION
 * -> LEXICAL_ANALYSIS
 * -> FREQUENCY_SIGNAL_DETECTION
 * -> ANCHOR_SIGNAL_DETECTION
 * -> CONTEXT_AGGREGATION
 * -> LINK_SIGNAL_DETECTION
 * -> TEMPORAL_SIGNAL_DETECTION
 * -> BEHAVIORAL_SIGNAL_DETECTION
 * -> QUERY_NORMALIZATION
 * -> QUERY_PROFILING
 * -> QUERY_DOCUMENT_SIGNAL_DETECTION
 * -> INTRINSIC_DOCUMENT_SCORING
 * -> TEMPORAL_DOCUMENT_SCORING
 * -> QUERY_RELEVANCE_SCORING
 * -> LINK_AUTHORITY_SCORING
 * -> BEHAVIORAL_CALIBRATION_SCORING
 * -> POSITIVE_SCORE_ASSEMBLY
 * -> PENALTY_EVALUATION
 * -> ANALYTICAL_AGGREGATION
 * -> ELIGIBILITY_EVALUATION
 *
 *      explicit distribution identity
 *      ↓
 *      SEARCH_COHORT_BATCH
 *
 * -> COHORT_NORMALIZATION
 * -> RELATIVE_COHORT_EVALUATION
 * -> PRIVATE_DECISION
 * -> PRIVATE_SNAPSHOT
 * -> TRANSFORMATION
 * -> PUBLIC_RANKING
 *
 * SEARCH COHORT BATCH GOVERNANCE
 * ----------------------------------------------------------------------------
 * SearchCohortBatch is a canonical transport boundary.
 *
 * It is NOT:
 * - an additional SearchPipelineLayer;
 * - a normalization layer;
 * - a statistical producer;
 * - a ranking layer.
 *
 * Its distribution_id:
 * - originates from resolve_distribution_id;
 * - is never generated by this orchestrator;
 * - is transported to build_cohort_batch;
 * - must be preserved by SearchCohortBatch;
 * - must be preserved by Cohort Normalization;
 * - must be preserved by Relative Cohort Evaluation.
 *
 * SearchCohortCandidate references:
 * - are projected once from canonical scored-document truth;
 * - enter SearchCohortBatch;
 * - must be preserved by SearchCohortBatch;
 * - must be reused unchanged for Relative Cohort Evaluation;
 * - must never be reconstructed downstream of SearchCohortBatch.
 *
 * COHORT NORMALIZATION OWNERSHIP
 * ----------------------------------------------------------------------------
 * COHORT_NORMALIZATION is the sole canonical owner of:
 * - SearchCohortDistribution;
 * - distribution statistics;
 * - cohort descriptive statistics;
 * - normalization-method truth.
 *
 * Runtime orchestration therefore MUST NOT recalculate:
 * - ranking eligible population count as normalization truth;
 * - mean;
 * - median;
 * - variance;
 * - standard deviation;
 * - percentile;
 * - relative position;
 * - normalization statistics.
 *
 * Runtime may consume ranking_eligible as an operational participation gate,
 * but it never turns that gate into replacement cohort statistics.
 *
 * TEMPORAL PROVENANCE GOVERNANCE
 * ----------------------------------------------------------------------------
 * Three temporal realities remain distinct:
 *
 * created_at
 * - explicit deterministic runtime / execution timestamp.
 *
 * publication_reference_at
 * - explicit analytical reference timestamp consumed by legitimate Temporal
 *   execution.
 *
 * source_published_at
 * - Acquisition-owned source publication evidence.
 *
 * The orchestrator MUST NOT derive one from another.
 *
 * In particular it must never substitute:
 * - fetched_at;
 * - created_at;
 * - publication_reference_at;
 * - observation timestamps;
 * - snapshot timestamps
 *
 * for source_published_at.
 *
 * TEMPORAL_SIGNAL_DETECTION remains the sole producer of derived temporal truth
 * such as publication_age_ms.
 *
 * Runtime orchestration never calculates publication age.
 *
 * QUERY GOVERNANCE
 * ----------------------------------------------------------------------------
 * SearchQueryProfile is canonical QUERY_PROFILING truth.
 *
 * Query Relevance Scoring receives:
 * - the canonical SearchQueryProfile;
 * - the canonical SearchQueryDocumentSignals.
 *
 * Runtime never reconstructs a profile from lower-level query information.
 *
 * POLICY / CALIBRATION GOVERNANCE
 * ----------------------------------------------------------------------------
 * Producer policies are absent from runtime orchestration.
 *
 * Policy resolution belongs to producer adapters.
 *
 * Calibration remains outside the current analytical execution.
 *
 * Runtime never:
 * - selects a policy;
 * - constructs a policy;
 * - supplies a DEFAULT_* policy;
 * - mutates a policy;
 * - executes calibration;
 * - infers thresholds.
 *
 * POSITIVE / NEGATIVE ANALYTICAL SEPARATION
 * ----------------------------------------------------------------------------
 * POSITIVE_SCORE_ASSEMBLY and PENALTY_EVALUATION remain independent branches.
 *
 * They meet only at ANALYTICAL_AGGREGATION.
 *
 * Runtime never feeds Positive Score Assembly truth into Penalty Evaluation.
 *
 * ELIGIBILITY GOVERNANCE
 * ----------------------------------------------------------------------------
 * SearchEligibilityResult is canonical ELIGIBILITY_EVALUATION truth.
 *
 * Runtime consumes:
 * - ranking_eligible for public participation;
 * - the complete canonical eligibility object for downstream producers.
 *
 * Runtime MUST NOT create additional semantic rules between eligibility fields.
 *
 * In particular it does not locally infer:
 *
 * allow_eligible -> ranking_eligible
 *
 * unless such a relationship is itself owned and enforced by the canonical
 * eligibility producer/contract.
 *
 * PRIVATE DECISION GOVERNANCE
 * ----------------------------------------------------------------------------
 * PRIVATE_DECISION solely owns BLOCK / WATCH / ALLOW.
 *
 * Runtime does not infer a decision category from:
 * - ranking_eligible;
 * - allow_eligible;
 * - cohort availability;
 * - relative-evaluation availability.
 *
 * PUBLIC PARTICIPATION GOVERNANCE
 * ----------------------------------------------------------------------------
 * ranking_eligible is upstream canonical participation truth.
 *
 * ranking-ineligible candidates never cross Transformation.
 *
 * Current snapshot/public path also requires an AVAILABLE canonical
 * SearchCohortDistribution.
 *
 * Therefore:
 *
 * ranking eligible
 * + cohort distribution AVAILABLE
 * -> private snapshot
 * -> transformation
 * -> public ranking candidate
 *
 * ranking eligible
 * + cohort distribution unavailable
 * -> private decision may still exist
 * -> no synthetic snapshot
 * -> no synthetic public candidate
 *
 * PUBLIC_RANKING remains sole producer of public_position / final ordering.
 *
 * TRACEABILITY GOVERNANCE
 * ----------------------------------------------------------------------------
 * resolve_snapshot_traceability transports existing:
 * - EXECUTION_TRACEABILITY truth;
 * - VARIABLE_LINEAGE_GOVERNANCE truth.
 *
 * Runtime does not create either truth.
 *
 * PRIVATE_SNAPSHOT consumes them.
 *
 * DIRECTIVES
 * - orchestration only
 * - canonical producers only
 * - explicit dependency injection
 * - explicit identity propagation
 * - explicit timestamp propagation
 * - explicit publication-reference propagation
 * - explicit source-publication propagation
 * - explicit distribution identity propagation
 * - canonical SearchCohortBatch transport
 * - exact SearchCohortCandidate reuse after SearchCohortBatch
 * - explicit optional evidence propagation
 * - no producer logic recreation
 * - no query-profile reconstruction
 * - no publication timestamp reconstruction
 * - no publication-age calculation
 * - no scoring calculation
 * - no threshold calculation
 * - no penalty calculation
 * - no aggregation calculation
 * - no eligibility calculation
 * - no cohort-statistic calculation
 * - no normalization calculation
 * - no relative-evaluation calculation
 * - no private-decision calculation
 * - no public-label calculation
 * - no public-position calculation
 * - no ranking calculation
 * - no policy resolution
 * - no policy mutation
 * - no calibration execution
 * - no hidden fallback
 * - no unavailable-to-zero conversion
 * - no unavailable-to-neutral conversion
 * - no synthetic score vector
 * - no synthetic cohort distribution
 * - no synthetic relative evaluation
 * - no runtime clock access
 * - no random identifier generation
 * - no direct HTTP dependency
 * - no persistence
 * - no logging
 *
 * INVARIANTS
 * - one execution belongs to exactly one query
 * - one execution belongs to exactly one cohort definition
 * - one SearchCohortBatch per non-empty scored execution
 * - one explicit distribution identity per SearchCohortBatch
 * - canonical SearchCohortCandidate references survive SearchCohortBatch
 * - Relative Cohort Evaluation receives the SearchCohortBatch candidate
 * - all query-scoped outputs preserve canonical query identity
 * - all document-scoped outputs preserve canonical document identity
 * - no duplicate acquired document identity is accepted
 * - created_at is explicit and never generated locally
 * - publication_reference_at is explicit and never reconstructed locally
 * - source_published_at remains Acquisition-owned
 * - Temporal published_at preserves source publication evidence
 * - snapshot raw publication evidence preserves Acquisition truth
 * - publication_age_ms is never calculated by orchestration
 * - Query Relevance receives canonical SearchQueryProfile
 * - concrete Temporal and Query Relevance score truth is never made optional
 * - optional Link Authority evidence remains optional
 * - optional Behavioral Calibration evidence remains optional
 * - penalty truth remains independent from positive-score truth
 * - eligibility is consumed and never reconstructed
 * - cohort distribution availability is consumed and never reconstructed
 * - relative evaluation availability is consumed and never reconstructed
 * - cohort statistics are never reconstructed locally
 * - ranking-ineligible candidates never cross Transformation
 * - unavailable cohort distribution prevents snapshot/public projection
 * - private decision category remains producer-owned
 * - snapshot identity originates from resolve_snapshot_id
 * - traces originate from resolve_snapshot_traceability
 * - public_position cannot exist before PUBLIC_RANKING
 * - final public ranking originates from PUBLIC_RANKING only
 * - no input contract is mutated
 * - no runtime clock is read
 * - no random identity is generated
 *
 * FIRST DIVERGENCE
 * ----------------------------------------------------------------------------
 * document identity changes
 * => producer propagation boundary
 *
 * query identity changes
 * => producer propagation boundary
 *
 * publication_reference_at reconstructed
 * => temporal provenance violation
 *
 * Temporal published_at differs from Acquisition source_published_at
 * => source publication propagation boundary
 *
 * fetched_at substituted for source_published_at
 * => source publication lineage violation
 *
 * publication_age_ms calculated here
 * => TEMPORAL_SIGNAL_DETECTION ownership violation
 *
 * QueryProfile disappears before Query Relevance
 * => QUERY_PROFILING propagation boundary
 *
 * optional Link / Behavioral evidence becomes fabricated score truth
 * => missing-data governance boundary
 *
 * Penalty Evaluation consumes Positive Score Assembly
 * => analytical branch violation
 *
 * distribution identity changes
 * => distribution propagation boundary
 *
 * SearchCohortBatch changes canonical candidate references
 * => SEARCH_COHORT_BATCH boundary
 *
 * SearchCohortCandidate reconstructed after SearchCohortBatch
 * => SEARCH_COHORT_BATCH propagation violation
 *
 * cohort statistics recalculated in orchestration
 * => COHORT_NORMALIZATION ownership violation
 *
 * unavailable cohort evidence becomes synthetic distribution
 * => missing-data governance violation
 *
 * unavailable relative evidence is reconstructed
 * => RELATIVE_COHORT_EVALUATION ownership violation
 *
 * private decision category inferred by runtime
 * => PRIVATE_DECISION ownership violation
 *
 * ranking-ineligible candidate reaches Transformation
 * => public participation violation
 *
 * public_position exists before Public Ranking
 * => PUBLIC_RANKING ownership violation
 * ========================================================================== */

