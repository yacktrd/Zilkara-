/* ============================================================================
 * 35. CANONICAL COHORT BATCH VALIDATION
 * ========================================================================== */

function validateCohortBatch(
  cohortBatch:
    SearchCohortBatch,

  cohortDefinition:
    SearchCohortDefinition,

  candidates:
    readonly SearchCohortCandidate[],

  distributionId:
    SearchDistributionId,

  queryId:
    SearchQueryId,
): void {
  assertNonEmptyString(
    cohortBatch.contract_version,
    "cohort_batch.contract_version",
  );

  assertValidIsoTimestamp(
    cohortBatch.created_at,
    "cohort_batch.created_at",
  );

  assertCohortScope(
    cohortBatch.cohort_id,
    cohortDefinition.cohort_id,
    "cohort_batch",
  );

  assertQueryScope(
    cohortBatch.query_id,
    queryId,
    "cohort_batch",
  );

  assertNonEmptyString(
    cohortBatch.distribution_id,
    "cohort_batch.distribution_id",
  );

  if (
    cohortBatch.distribution_id !==
    distributionId
  ) {
    throw new Error(
      `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
        "Boundary violation: SearchCohortBatch changed canonical distribution identity.",
    );
  }

  if (
    cohortBatch.cohort_definition !==
    cohortDefinition
  ) {
    throw new Error(
      `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
        "Boundary violation: SearchCohortBatch does not preserve canonical cohort definition reference.",
    );
  }

  if (
    cohortBatch.candidate_count !==
    candidates.length
  ) {
    throw new Error(
      `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
        "Boundary violation: SearchCohortBatch candidate_count diverges from its canonical transport input.",
    );
  }

  if (
    cohortBatch.candidates.length !==
    candidates.length
  ) {
    throw new Error(
      `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
        "Boundary violation: SearchCohortBatch candidate collection cardinality diverges.",
    );
  }

  for (
    let index =
      0;
    index <
    candidates.length;
    index +=
      1
  ) {
    if (
      cohortBatch.candidates[
        index
      ] !==
      candidates[
        index
      ]
    ) {
      throw new Error(
        `[${XYVALA_SEARCH_RUNTIME_ORCHESTRATOR_MODULE_NAME}] ` +
          `Boundary violation: SearchCohortBatch candidate ${String(index)} does not preserve canonical candidate reference.`,
      );
    }
  }

  assertAuthorizedValidationState(
    cohortBatch.validation_state,
    "cohort_batch",
  );
}

